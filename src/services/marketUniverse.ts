// Seed Historical Data Generator (Deterministic & Verified)
export function generateRealisticHistoricalOHLCV(
  basePrice: number,
  volatility: number,
  trendBias: number,
  days = 120
): OHLCVBar[] {
  const bars: OHLCVBar[] = [];
  let currentClose = basePrice * (1 - (trendBias * days) / 100);
  const now = new Date('2026-11-02T16:00:00Z');

  for (let i = days; i >= 0; i--) {
    const barDate = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    // Skip weekends
    if (barDate.getUTCDay() === 0 || barDate.getUTCDay() === 6) continue;

    // Pseudo-random deterministic walk
    const seed = Math.sin(barDate.getTime()) * 10000;
    const randomNorm = (seed - Math.floor(seed)) - 0.48; // slight upward drift
    const dailyReturn = (trendBias / 100) + randomNorm * (volatility / 100);

    const open = Number((currentClose * (1 + (randomNorm * 0.3 * volatility) / 100)).toFixed(2));
    const close = Number((currentClose * (1 + dailyReturn)).toFixed(2));
    const high = Number((Math.max(open, close) + Math.abs(randomNorm) * volatility * 0.8).toFixed(2));
    const low = Number((Math.min(open, close) - Math.abs(randomNorm) * volatility * 0.8).toFixed(2));
    const volume = Math.floor(1500000 + Math.abs(randomNorm) * 2000000);

    bars.push({
      time: barDate.toISOString().split('T')[0],
      open,
      high,
      low,
      close,
      volume,
    });

    currentClose = close;
  }
  return bars;
}

